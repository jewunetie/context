const split = (lines) => lines.map((line) => line.trim().split(/\s+/));

/** form -> base, for the verb and plural tables. */
export const IRREGULAR = new Map();
for (const [base, ...forms] of split([...VERBS, ...PLURALS])) {
  for (const form of forms) IRREGULAR.set(form, base);
}

/** UK stem -> US stem. */
export const SPELLING_STEMS = new Map();
for (const [uk, us] of split(SPELLING)) SPELLING_STEMS.set(porter2(uk), porter2(us));

/**
 * The stored term for one lowercase a-z-and-apostrophe word of two or more
 * characters. A trailing possessive is dropped for the lookup only (Porter2
 * drops it anyway), so "children's" meets "child".
 */
export function stemmed(word) {
  const base = IRREGULAR.get(word.replace(/'s?$/, "")) ?? word;
  const stem = porter2(base);
  return SPELLING_STEMS.get(stem) ?? stem;
}
